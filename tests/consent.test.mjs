import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm,cp,readFile,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
import {openStore,tx,saveBooks,putUser,passwordHash} from '../store.mjs';
import {sampleVault} from '../shared/sample.mjs';
import {createSuite} from '../server.mjs';
import {termsVersion,termsText} from '../web/legal/terms.mjs';
const digest=text=>createHash('sha256').update(text.replace(/\r\n?/g,'\n')).digest('hex');
const password='Fictional assent test only 421';
async function client(url,username){
 let cookie='',csrf='';
 const request=async(path,data)=>{
  const response=await fetch(url+'/api/'+path,{method:data===undefined?'GET':'POST',headers:{Origin:url,Cookie:cookie,'X-CSRF-Token':csrf,'Content-Type':'application/json'},body:data===undefined?undefined:JSON.stringify(data)});
  const body=await response.json();if(response.headers.has('set-cookie'))cookie=response.headers.get('set-cookie').split(';')[0];if(body.csrf)csrf=body.csrf;
  return {status:response.status,body};
 };
 return {request,login:await request('login',{username,password})};
}
test('legacy assent migrates without changing books; each user/version/hash remains independently gated',async()=>{
 const dir=await mkdtemp(join(tmpdir(),'fq-consent-')),database=join(dir,'fictional.sqlite'),state=sampleVault();let suite;
 try{
  const db=openStore(database),encoded=await passwordHash(password);let owner,worker;
  try{tx(db,()=>{
   saveBooks(db,state);owner=putUser(db,null,{username:'owner',name:'Fictional Owner',role:'owner',assignments:[]},encoded,{bootstrap:true});
   worker=putUser(db,{id:owner,role:'owner'},{username:'worker',name:'Fictional Worker',role:'worker',assignments:[state.companies[0].id],employeeId:state.companies[0].employees[0].id},encoded);
   db.prepare('INSERT INTO terms_acceptances VALUES(?,?,?)').run(owner,termsVersion,'2026-11-25T00:00:00.000Z');
  });}finally{db.close()}
  suite=await createSuite({database,mainPort:0,workerPort:0});
  let a=await client(suite.mainUrl,'owner'),w=await client(suite.workerUrl,'worker');
  assert.deepEqual(a.login.body.state,state);assert.equal(w.login.body.termsRequired,termsVersion);
  assert.equal((await w.request('worker/action',{})).status,428);
  // Decline means no write. Re-login must still require terms.
  await w.request('logout',{});w=await client(suite.workerUrl,'worker');assert.equal(w.login.body.termsRequired,termsVersion);
  assert.equal((await w.request('terms',{version:termsVersion,hash:'0'.repeat(64)})).status,409);
  assert.equal((await w.request('terms',{version:termsVersion,hash:digest(termsText)})).status,200);
  await w.request('logout',{});w=await client(suite.workerUrl,'worker');assert.equal(w.login.body.termsRequired,undefined);
  await suite.close();suite=null;
  // A code-only restart retains verified assent for both users.
  suite=await createSuite({database,mainPort:0,workerPort:0});a=await client(suite.mainUrl,'owner');w=await client(suite.workerUrl,'worker');
  assert.deepEqual(a.login.body.state,state);assert.equal(w.login.body.termsRequired,undefined);
  await suite.close();suite=null;
  // Load a separate copy with a hypothetical changed approved version/text.
  const variant=join(dir,'variant');await cp(new URL('../',import.meta.url),variant,{recursive:true,filter:source=>!/[\\/](\.git|tests|lite-tests)([\\/]|$)/.test(source)});
  const file=join(variant,'web/legal/terms.mjs');let source=await readFile(file,'utf8');
  source=source.replace("termsVersion = '1.0'","termsVersion = '1.1'").replace('Version 1.0 ','Version 1.1 ');await writeFile(file,source);
  const next=await import(pathToFileURL(join(variant,'server.mjs'))),terms=await import(pathToFileURL(file));
  suite=await next.createSuite({database,mainPort:0,workerPort:0});a=await client(suite.mainUrl,'owner');w=await client(suite.workerUrl,'worker');
  assert.equal(a.login.body.termsRequired,'1.1');assert.equal(w.login.body.termsRequired,'1.1');assert.equal((await a.request('admin/users')).status,428);
  assert.equal((await a.request('terms',{version:'1.1',hash:digest(terms.termsText)})).status,200);
  assert.deepEqual((await a.request('session')).body.state,state);assert.equal((await w.request('worker/action',{})).status,428);
  await suite.close();suite=null;
  source=source.replace('This product was generated by AI.','This product was generated by AI. Fictional text-only update.');await writeFile(file,source);
  const changed=join(dir,'same-version-variant');await cp(variant,changed,{recursive:true});
  const updated=await import(pathToFileURL(join(changed,'server.mjs')));
  suite=await updated.createSuite({database,mainPort:0,workerPort:0});a=await client(suite.mainUrl,'owner');
  assert.equal(a.login.body.termsRequired,'1.1');assert.equal((await a.request('admin/users')).status,428);
  await suite.close();suite=null;
  // Verify a current hash cannot be confused with a same-version different hash.
  const check=openStore(database);try{
   assert.equal(check.prepare('SELECT count(*) AS n FROM terms_acceptance_hashes WHERE account_id=? AND version=? AND content_hash=?').get(owner,'1.1',digest(terms.termsText+'\nChanged')).n,0);
   assert.deepEqual(JSON.parse(check.prepare('SELECT body FROM books').get().body),state);
   assert.equal(check.prepare('SELECT accepted_at FROM terms_acceptances WHERE account_id=?').get(owner).accepted_at,'2026-11-25T00:00:00.000Z');
  }finally{check.close()}
 }finally{if(suite)await suite.close();await rm(dir,{recursive:true,force:true})}
});
